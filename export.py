# non-character keys every keyMap needs: return, tab, space, delete, escape, navigation, F-keys, keypad
MAC_SPECIAL = {
    36: "&#x000D;", 48: "&#x0009;", 49: " ", 51: "&#x0008;", 53: "&#x001B;", 76: "&#x0003;",
    114: "&#x0005;", 115: "&#x0001;", 116: "&#x000B;", 117: "&#x007F;", 119: "&#x0004;",
    121: "&#x000C;", 123: "&#x001C;", 124: "&#x001D;", 125: "&#x001F;", 126: "&#x001E;",
    **{c: "&#x0010;" for c in (96, 97, 98, 99, 100, 101, 103, 105, 106, 107, 109, 111, 113, 118, 120, 122)},
    65: ".", 67: "*", 69: "+", 71: "&#x001B;", 75: "/", 78: "-", 81: "=",
    **{code: str(d) for d, code in enumerate((82, 83, 84, 85, 86, 87, 88, 89, 91, 92))},
}


def xml_attr(ch: str) -> str:
    return {"&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;"}.get(ch, ch)


def to_keylayout(layout: dict, name: str) -> str:
    """macOS layout. Command and Control use QWERTY, so shortcuts stay in QWERTY places."""
    maps = {
        0: {lab: layout[lab][0] for lab in LABELS},
        1: {lab: layout[lab][1] for lab in LABELS},
        2: {lab: lo.upper() if lo.isalpha() else lo for lab, (lo, _) in
            ((lab, layout[lab]) for lab in LABELS)},
        3: {lab: QWERTY[lab][0] for lab in LABELS},
    }
    body = []
    for index, chars in maps.items():
        body.append(f'\t\t<keyMap index="{index}">')
        keys = {MAC_CODES[lab]: xml_attr(ch) for lab, ch in chars.items()} | MAC_SPECIAL
        body += [f'\t\t\t<key code="{code}" output="{out}"/>' for code, out in sorted(keys.items())]
        body.append("\t\t</keyMap>")
    kid = -(zlib.crc32(name.encode()) % 30000 + 2)
    return f"""<?xml version="1.1" encoding="UTF-8"?>
<!DOCTYPE keyboard SYSTEM "file://localhost/System/Library/DTDs/KeyboardLayout.dtd">
<!-- {name} (generated by layout-optimizer/export.py) -->
<keyboard group="126" id="{kid}" name="{name}" maxout="1">
\t<layouts>
\t\t<layout first="0" last="255" mapSet="ansi" modifiers="mods"/>
\t</layouts>
\t<modifierMap id="mods" defaultIndex="0">
\t\t<keyMapSelect mapIndex="0">
\t\t\t<modifier keys=""/>
\t\t</keyMapSelect>
\t\t<keyMapSelect mapIndex="1">
\t\t\t<modifier keys="anyShift caps?"/>
\t\t</keyMapSelect>
\t\t<keyMapSelect mapIndex="2">
\t\t\t<modifier keys="caps"/>
\t\t</keyMapSelect>
\t\t<keyMapSelect mapIndex="3">
\t\t\t<modifier keys="anyShift? caps? anyOption? command anyControl?"/>
\t\t\t<modifier keys="anyShift? caps? anyOption? anyControl"/>
\t\t</keyMapSelect>
\t</modifierMap>
\t<keyMapSet id="ansi">
{chr(10).join(body)}
\t</keyMapSet>
</keyboard>
"""


# --- CLI ----------------------------------------------------------------------------
FORMATS = {
    "ahk": (".ahk", to_ahk, "utf-8"),
    "kanata": (".kbd", to_kanata, "utf-8"),
    "klc": (".klc", to_klc, "utf-16"),  # MSKLC expects UTF-16 with a BOM
    "keylayout": (".keylayout", to_keylayout, "utf-8"),
}


def load_layout(spec: str) -> tuple[dict, str, Path]:
    """(layout, display name, folder) for a layout folder, its layout.json, or a known layout name."""
    if spec in LAYOUTS:
        name = BASE_NAMES[spec]
        return LAYOUTS[spec], name, LAYOUTS_DIR / slug(name)
    path = Path(spec)
    if path.is_dir():
        path = path / "layout.json"
    data = json.loads(path.read_text())
    name = data.get("name") or path.parent.name.replace("-", " ").title()
    return {k: tuple(v) for k, v in data["layout"].items()}, name, path.parent


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--layout", default=str(LAYOUTS_DIR / "python-programmer-dvorak"),
                    help=f"a layout folder (or its layout.json) or a layout name: {', '.join(LAYOUTS)}")
    ap.add_argument("--format", choices=[*FORMATS, "all"], default="all")
    ap.add_argument("--name", help="layout name shown by the OS/tooltip (default: from layout.json)")
    args = ap.parse_args()

    layout, name, folder = load_layout(args.layout)
    name = args.name or name
    folder.mkdir(parents=True, exist_ok=True)
    for fmt in FORMATS if args.format == "all" else [args.format]:
        ext, render, encoding = FORMATS[fmt]
        out = folder / (folder.name + ext)
        text = render(layout, name)
        if fmt == "klc":
            text = text.replace("\n", "\r\n")
        out.write_text(text, encoding=encoding, newline="")
        print(f"wrote {out}")


if __name__ == "__main__":
    main()
