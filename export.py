"""Export a layout (a layout folder or a known layout name) as a remapper script or native layout.

Formats:
  ahk        AutoHotkey v2 script (Windows); remaps on top of a QWERTY OS layout
  kanata     kanata config (Windows, macOS, Linux); remaps on top of a QWERTY OS layout
  klc        Microsoft Keyboard Layout Creator source (build a Windows layout with MSKLC)
  keylayout  macOS keyboard layout (copy to ~/Library/Keyboard Layouts, then add it in Settings)

The remappers keep the standard extras: Right Shift + WASD = arrows, Caps Lock toggles plain
QWERTY, Shift+Caps Lock is Caps Lock, and Ctrl/Alt/Win shortcuts stay on QWERTY positions.
Native layouts can't do the arrows or the toggle, but keep shortcuts on QWERTY positions too.

Each layout lives in its own folder, layouts/<name>/, next to its layout.json (written by
optimize.py); the exports go into that folder as <name>.ahk, .kbd, .klc and .keylayout.

Usage: python export.py [--layout layouts/python-programmer-dvorak | qwerty | ...] [--format all]
"""
import argparse
import json
import re
import zlib
from pathlib import Path

from model import BASE_NAMES, LAYOUTS, LAYOUTS_DIR, ROWS, Keyboard, slug

KB = Keyboard()
QWERTY = LAYOUTS["qwerty"]
# char -> (QWERTY key label, shifted) on a US QWERTY OS layout
QWERTY_CHAR = {ch: (label, s) for label, pair in QWERTY.items() for s, ch in enumerate(pair)}
LABELS = [lab for row in ROWS for lab, _ in row]
WASD_ARROWS = {"w": "Up", "a": "Left", "s": "Down", "d": "Right"}

# --- AutoHotkey ---------------------------------------------------------------------
AHK_TEMPLATE = """#Requires AutoHotkey v2.0
#SingleInstance Force

; {name} (generated by layout-optimizer/export.py)
; - Plain and Shift keypresses type the layout below.
; - Ctrl/Alt/Win combos aren't touched, so shortcuts stay in their QWERTY positions.
; - Right Shift + physical WASD = arrow keys (Left Shift/Ctrl still combine:
;   RShift+LShift+D selects right, RShift+Ctrl+A jumps a word left).
; - Caps Lock toggles back to plain QWERTY (e.g. for games); Shift+Caps Lock is Caps Lock.

; physical key (scan code) -> [normal, shifted]
layout := Map(
{rows}
)

arrows := Map("SC011", "Up", "SC01E", "Left", "SC01F", "Down", "SC020", "Right")

; Caps Lock toggles plain QWERTY (everything below is off).
qwertyMode := false

; Right Shift + WASD: arrows, with any other held modifiers passed through.
HotIf (*) => !qwertyMode && GetKeyState("RShift", "P")
for sc, key in arrows
    Hotkey "*" sc, SendArrow.Bind(key)
HotIf

; Layout typing; yields WASD to the arrows above while Right Shift is held.
HotIf (hk) => !qwertyMode && !(GetKeyState("RShift", "P") && arrows.Has(LTrim(hk, "+")))
for sc, chars in layout {{
    Hotkey sc, TypeKey.Bind(chars, false)
    Hotkey "+" sc, TypeKey.Bind(chars, true)
}}
HotIf

TypeKey(chars, shifted, *) {{
    ; Caps Lock flips case for letters only, like a normal layout.
    if IsAlpha(chars[1]) && GetKeyState("CapsLock", "T")
        shifted := !shifted
    SendText(chars[shifted ? 2 : 1])
}}

; Lift Right Shift around the arrow so it moves instead of selecting.
SendArrow(key, *) => Send("{{Blind}}{{RShift up}}{{" key "}}{{RShift down}}")

CapsLock:: {{
    global qwertyMode := !qwertyMode
    ToolTip qwertyMode ? "QWERTY" : "{name}"
    SetTimer () => ToolTip(), -1000
}}

+CapsLock::SetCapsLockState !GetKeyState("CapsLock", "T")
"""

ROW_NAMES = ["number row", "top row", "home row", "bottom row"]


def ahk_str(ch: str) -> str:
    """AHK v2 string literal for one character."""
    if ch == '"':
        return "'\"'"
    if ch == "`":
        return '"``"'
    return f'"{ch}"'


def to_ahk(layout: dict, name: str) -> str:
    lines = []
    by_label = {k.label: k for k in KB.keys}
    for r, row in enumerate(ROWS):
        labels = [lab for lab, _ in row]
        lines.append(f"    ; {ROW_NAMES[r]}: {' '.join(labels)}")
        entries = [f'"{by_label[lab].scancode}", [{ahk_str(layout[lab][0])}, {ahk_str(layout[lab][1])}]'
                   for lab in labels]
        for i in range(0, len(entries), 4):
            last = r == len(ROWS) - 1 and i + 4 >= len(entries)
            lines.append("    " + ", ".join(entries[i:i + 4]) + ("" if last else ","))
    return AHK_TEMPLATE.format(name=name, rows="\n".join(lines))


# --- kanata -------------------------------------------------------------------------
KANATA_NAMES = {"`": "grv"}  # other keys are named by their QWERTY character
MODS = "(lctl rctl lalt ralt lmet rmet)"


def kname(label: str) -> str:
    return KANATA_NAMES.get(label, label)


def kanata_out(ch: str, shift_held: bool) -> str:
    """kanata action typing ch through a QWERTY OS layout."""
    label, shifted = QWERTY_CHAR[ch]
    if shifted:
        return f"S-{kname(label)}"
    return f"(unshift {kname(label)})" if shift_held else kname(label)


def to_kanata(layout: dict, name: str) -> str:
    src = (["grv", *"1234567890-="], [*"qwertyuiop[]\\"], ["caps", *"asdfghjkl;'"],
           ["lsft", *"zxcvbnm,./", "rsft"])
    aliases, base, nav, qwerty = [], [], [], []
    for i, label in enumerate(LABELS):
        lo, hi = layout[label]
        k = kname(label)
        typed_hi = kanata_out(hi, shift_held=True)
        aliases.append(f"  k{i} (fork (fork {kanata_out(lo, False)} {typed_hi} (lsft rsft)) {k} {MODS})"
                       f"  ;; {label}: {lo} {hi}")
        aliases.append(f"  n{i} (fork {typed_hi} S-{k} {MODS})")
    by_name = {kname(lab): i for i, lab in enumerate(LABELS)}
    for row in src:
        b, n, q = [], [], []
        for k in row:
            if k in by_name:
                i = by_name[k]
                b.append(f"@k{i}")
                n.append(WASD_ARROWS.get(k, "").lower().replace("right", "rght") or f"@n{i}")
                q.append(k)
            elif k == "caps":
                b.append("@caps"), n.append("caps"), q.append("@base")
            elif k == "rsft":
                b.append("@rnav"), n.append("_"), q.append("rsft")
            else:
                b.append(k), n.append(k), q.append(k)
        base.append(" ".join(b)), nav.append(" ".join(n)), qwerty.append(" ".join(q))

    def block(rows):
        return "\n".join("  " + r for r in rows)

    return f""";; {name} (generated by layout-optimizer/export.py)
;; Run kanata with the OS keyboard layout set to US QWERTY.
;; - Plain and Shift keypresses type the layout; with Ctrl/Alt/Win held, keys stay QWERTY.
;; - Right Shift + WASD = arrows (Left Shift/Ctrl still combine); with other keys Right Shift
;;   acts as Shift.
;; - Caps Lock toggles plain QWERTY; Shift+Caps Lock is Caps Lock.

(defcfg
  process-unmapped-keys yes
)

(defsrc
{block([" ".join(r) for r in src])}
)

(defalias
  caps (fork (layer-switch qwerty) caps (lsft rsft))
  base (fork (layer-switch base) caps (lsft rsft))
  rnav (layer-while-held rnav)
{chr(10).join(aliases)}
)

(deflayer base
{block(base)}
)

;; Right Shift held: shifted characters, WASD = arrows
(deflayer rnav
{block(nav)}
)

(deflayer qwerty
{block(qwerty)}
)
"""


