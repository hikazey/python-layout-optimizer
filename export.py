def klc_char(ch: str) -> str:
    return ch if ch.isalnum() else f"{ord(ch):04x}"


def klc_line(sc: str, vk: str, lo: str, hi: str) -> str:
    cap = int(lo.isalpha() and hi == lo.upper())
    return (f"{sc}\t{vk}\t\t{cap}\t{klc_char(lo)}\t{klc_char(hi)}\t-1\t\t"
            f"// {lo} {hi}")


def to_klc(layout: dict, name: str) -> str:
    """MSKLC source. Virtual keys follow QWERTY, so Ctrl/Alt/Win shortcuts stay in QWERTY places."""
    # the 8-char DLL name must be unique per installed layout, so add a hash of the full name
    kbd = (re.sub(r"[^A-Za-z0-9]", "", name)[:4] or "LYT") + f"{zlib.crc32(name.encode()) % 0x10000:04x}"
    lines = []
    for k in KB.keys:
        vk = KLC_VK.get(k.label, k.label.upper())
        lines.append(klc_line(k.scancode[2:].lower().lstrip("0").rjust(2, "0"), vk, *layout[k.label]))
    lines.append(klc_line("56", "OEM_102", *layout["\\"]))  # ISO key next to Left Shift
    lines.append("39\tSPACE\t\t0\t0020\t0020\t0020\t\t// space")
    lines.append("53\tDECIMAL\t\t0\t002e\t002e\t-1\t\t// numpad .")
    return f"""KBD\t{kbd}\t"{name}"

COPYRIGHT\t"(c) generated by layout-optimizer"

COMPANY\t"layout-optimizer"

LOCALENAME\t"en-US"

LOCALEID\t"00000409"

VERSION\t1.0

SHIFTSTATE

0\t//Column 4
1\t//Column 5 : Shft
2\t//Column 6 :       Ctrl

LAYOUT\t\t;an extra '@' at the end is a dead key

//SC\tVK_\t\tCap\t0\t1\t2
//--\t----\t\t----\t----\t----\t----

{chr(10).join(lines)}

{KLC_KEYNAMES}
DESCRIPTIONS

0409\t{name}

LANGUAGENAMES

0409\tEnglish (United States)

ENDKBD
"""


